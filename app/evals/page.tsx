import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';

export const dynamic = 'force-static';

interface AssessmentScorecard {
  generatedAt: string;
  corpusVersion: string;
  models: { fast: string; deep: string };
  splits: Record<
    string,
    { total: number; correct: number; accuracy: number }
  >;
  confusion: Record<string, Record<string, number>>;
  citationFaithfulness: { totalCitations: number; resolved: number; rate: number };
  cost: { meanEurPerAssessment: number; totalEur: number };
  latency: { p50Ms: number; p95Ms: number };
  failures: { id: string; expected: string; predicted: string }[];
}

interface RetrievalScorecard {
  generatedAt: string;
  corpusVersion: string;
  configs: { name: string; recallAt5: number; mrr: number; queries: number }[];
}

interface ProbeScorecard {
  generatedAt: string;
  probes: { id: string; kind: string; passed: boolean; note: string }[];
}

function load<T>(name: string): T | null {
  const p = path.join(process.cwd(), 'evals', 'results', name);
  return existsSync(p) ? (JSON.parse(readFileSync(p, 'utf8')) as T) : null;
}

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

export default function EvalsPage() {
  const assessment = load<AssessmentScorecard>('assessment-scorecard.json');
  const retrieval = load<RetrievalScorecard>('retrieval-scorecard.json');
  const probes = load<ProbeScorecard>('probe-scorecard.json');

  return (
    <div className="space-y-8">
      <section>
        <h1 className="text-2xl font-semibold tracking-tight">Evals</h1>
        <p className="mt-2 text-sm text-stone-600">
          Every number on this page is read from committed eval artifacts in{' '}
          <code className="rounded bg-stone-100 px-1">evals/results/</code> — generated by{' '}
          <code className="rounded bg-stone-100 px-1">npm run evals</code>, gated in CI, and printed
          whether or not they flatter the system. Methodology and the labelling rubric:{' '}
          <a className="underline" href="/methodology">/methodology</a>.
        </p>
      </section>

      {!assessment && !retrieval && !probes && (
        <p className="rounded-md border border-stone-200 bg-white p-4 text-sm text-stone-600">
          No eval artifacts committed yet. Run <code>npm run evals</code> (needs GOOGLE_API_KEY),
          then <code>npm run evals:retrieval</code> and <code>npm run evals:probes</code>.
        </p>
      )}

      {assessment && (
        <section className="rounded-lg border border-stone-200 bg-white p-5">
          <h2 className="font-semibold">Classification accuracy</h2>
          <p className="mt-1 text-xs text-stone-500">
            Golden set labelled against the published rubric. Core = labels that fall near-deterministically
            out of Article 5 / Annex III / Article 50. Contested = genuinely arguable cases; treat that number
            as agreement with one documented reading, not ground truth.
          </p>
          <table className="mt-3 w-full text-sm">
            <thead>
              <tr className="border-b border-stone-200 text-left text-xs text-stone-500">
                <th className="py-1.5">Split</th>
                <th>Cases</th>
                <th>Correct</th>
                <th>Accuracy</th>
              </tr>
            </thead>
            <tbody>
              {Object.entries(assessment.splits).map(([split, s]) => (
                <tr key={split} className="border-b border-stone-100">
                  <td className="py-1.5 font-medium">{split}</td>
                  <td>{s.total}</td>
                  <td>{s.correct}</td>
                  <td>{pct(s.accuracy)}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <div className="mt-3 grid grid-cols-2 gap-3 text-sm sm:grid-cols-4">
            <Stat label="citation faithfulness" value={pct(assessment.citationFaithfulness.rate)} sub={`${assessment.citationFaithfulness.resolved}/${assessment.citationFaithfulness.totalCitations} resolve`} />
            <Stat label="mean cost" value={`€${assessment.cost.meanEurPerAssessment.toFixed(4)}`} sub="per assessment" />
            <Stat label="latency p50" value={`${(assessment.latency.p50Ms / 1000).toFixed(1)}s`} sub={`p95 ${(assessment.latency.p95Ms / 1000).toFixed(1)}s`} />
            <Stat label="models" value={assessment.models.deep.replace('gemini-', '')} sub={`+ ${assessment.models.fast.replace('gemini-', '')}`} />
          </div>
          {assessment.failures.length > 0 && (
            <details className="mt-3 text-xs text-stone-600">
              <summary className="cursor-pointer font-medium">Misclassifications ({assessment.failures.length})</summary>
              <ul className="mt-1 space-y-0.5">
                {assessment.failures.map((f) => (
                  <li key={f.id}>
                    <code>{f.id}</code>: expected {f.expected}, predicted {f.predicted}
                  </li>
                ))}
              </ul>
            </details>
          )}
          <p className="mt-2 text-xs text-stone-400">
            Run {assessment.generatedAt} · corpus {assessment.corpusVersion}
          </p>
        </section>
      )}

      {retrieval && (
        <section className="rounded-lg border border-stone-200 bg-white p-5">
          <h2 className="font-semibold">Retrieval scorecard</h2>
          <p className="mt-1 text-xs text-stone-500">
            Query = each golden case description; relevant docs = the articles/annexes in its labelled
            legal basis. Recall@5 = share of cases where a basis document appears in the top-5 retrieved
            parents.
          </p>
          <table className="mt-3 w-full text-sm">
            <thead>
              <tr className="border-b border-stone-200 text-left text-xs text-stone-500">
                <th className="py-1.5">Config</th>
                <th>Queries</th>
                <th>Recall@5</th>
                <th>MRR</th>
              </tr>
            </thead>
            <tbody>
              {retrieval.configs.map((c) => (
                <tr key={c.name} className="border-b border-stone-100">
                  <td className="py-1.5 font-medium">{c.name}</td>
                  <td>{c.queries}</td>
                  <td>{pct(c.recallAt5)}</td>
                  <td>{c.mrr.toFixed(3)}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <p className="mt-2 text-xs text-stone-400">Run {retrieval.generatedAt} · corpus {retrieval.corpusVersion}</p>
        </section>
      )}

      {probes && (
        <section className="rounded-lg border border-stone-200 bg-white p-5">
          <h2 className="font-semibold">Injection probes</h2>
          <p className="mt-1 text-xs text-stone-500">
            Adversarial inputs that try to steer the classification — including one indirect injection
            planted inside retrieved context. A pass means the pipeline ignored the instruction. A finite
            probe set proves the defences fire on these probes; it cannot prove absence of injection risk.
          </p>
          <ul className="mt-3 space-y-1.5 text-sm">
            {probes.probes.map((p) => (
              <li key={p.id} className="flex gap-2">
                <span className={p.passed ? 'text-green-700' : 'text-red-700'}>{p.passed ? '✓' : '✗'}</span>
                <span>
                  <span className="font-medium">{p.kind}</span> — {p.note}
                </span>
              </li>
            ))}
          </ul>
          <p className="mt-2 text-xs text-stone-400">Run {probes.generatedAt}</p>
        </section>
      )}
    </div>
  );
}

function Stat({ label, value, sub }: { label: string; value: string; sub: string }) {
  return (
    <div className="rounded-md bg-stone-50 p-2.5">
      <div className="font-semibold text-stone-800">{value}</div>
      <div className="text-xs text-stone-500">{label}</div>
      <div className="text-xs text-stone-400">{sub}</div>
    </div>
  );
}
